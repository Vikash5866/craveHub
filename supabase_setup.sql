create table if not exists public.orders (
    order_number bigint generated by default as identity primary key,
    legacy_id text unique,
    created_at timestamptz not null default now(),
    customer text not null default '',
    items jsonb not null check (jsonb_typeof(items) = 'array'),
    total numeric(12, 2) not null check (total >= 0)
);

alter table public.orders enable row level security;

grant usage on schema public to authenticated;
grant select, insert, delete on table public.orders to authenticated;
grant usage, select on sequence public.orders_order_number_seq to authenticated;

drop policy if exists "Staff can read orders" on public.orders;
create policy "Staff can read orders"
    on public.orders for select
    to authenticated
    using (true);

drop policy if exists "Staff can add orders" on public.orders;
create policy "Staff can add orders"
    on public.orders for insert
    to authenticated
    with check (true);

drop policy if exists "Staff can delete orders" on public.orders;
create policy "Staff can delete orders"
    on public.orders for delete
    to authenticated
    using (true);
